CREATE TABLE IF NOT EXISTS users(steamid TEXT PRIMARY KEY,name TEXT,vis TEXT DEFAULT 'friends',avatar TEXT,fr_at INTEGER DEFAULT 0,fr_n INTEGER);
CREATE TABLE IF NOT EXISTS rl(k TEXT PRIMARY KEY,n INTEGER NOT NULL,reset INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,steamid TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS games(
 id INTEGER PRIMARY KEY AUTOINCREMENT,steamid TEXT NOT NULL,appid INTEGER NOT NULL,name TEXT NOT NULL,
 hours REAL DEFAULT 0,genres TEXT DEFAULT '[]',ttb INTEGER,status TEXT DEFAULT 'plan',score INTEGER DEFAULT 0,
 review TEXT DEFAULT '',enriched INTEGER DEFAULT 0,platforms TEXT,fav INTEGER DEFAULT 0,tries INTEGER DEFAULT 0,UNIQUE(steamid,appid));
CREATE TABLE IF NOT EXISTS friends(steamid TEXT NOT NULL,friend TEXT NOT NULL,PRIMARY KEY(steamid,friend));
CREATE INDEX IF NOT EXISTS friends_rev ON friends(friend);
